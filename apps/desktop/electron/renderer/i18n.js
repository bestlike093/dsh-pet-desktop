  const DICTS = { 'zh-CN': ZH, 'en-US': EN }

  /** 取文案。缺失时返回 undefined，调用方保留原文本。 */
  function t(key, locale) {
    const dict = DICTS[locale] ?? ZH
    const value = dict[key]
    if (typeof value === 'string') return value
    return ZH[key]
  }

  /** 把当前语言应用到整棵文档树。 */
  function apply(locale) {
    const resolved = DICTS[locale] === undefined ? 'zh-CN' : locale
    document.documentElement.lang = resolved

    for (const node of document.querySelectorAll('[data-i18n]')) {
      const text = t(node.dataset.i18n, resolved)
      if (typeof text === 'string') node.textContent = text
    }

    for (const node of document.querySelectorAll('[data-i18n-placeholder]')) {
      const text = t(node.dataset.i18nPlaceholder, resolved)
      if (typeof text === 'string') node.setAttribute('placeholder', text)
    }

    // title / aria-label 是属性文案，textContent 覆盖不到，单独走一遍。
    for (const node of document.querySelectorAll('[data-i18n-title]')) {
      const text = t(node.dataset.i18nTitle, resolved)
      if (typeof text === 'string') node.setAttribute('title', text)
    }

    for (const node of document.querySelectorAll('[data-i18n-aria-label]')) {
      const text = t(node.dataset.i18nAriaLabel, resolved)
      if (typeof text === 'string') node.setAttribute('aria-label', text)
    }
  }

  window.PetI18n = { t, apply, locales: ['zh-CN', 'en-US'] }
